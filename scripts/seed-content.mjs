// Generates supabase/migrations/20261101000013_course_content.sql from seed/lessons/*.json and seed/mocks/*.json.
// Run scripts/validate-content.mjs first.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'

const root = new URL('..', import.meta.url)
const read = dir => readdirSync(new URL(dir, root)).filter(f => f.endsWith('.json')).sort()
  .map(f => JSON.parse(readFileSync(new URL(dir + f, root), 'utf8')))
const lit = v => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const json = v => `${lit(JSON.stringify(v))}::jsonb`

const specSrc = readFileSync(new URL('src/lib/spec.ts', root), 'utf8')
const order = [...specSrc.matchAll(/t\((\d), '[^']*', '([\d.]+)', '[^']+'/g)].map(m => m[2])

const lessons = read('seed/lessons/').flat().sort((a, b) => order.indexOf(a.topic_code) - order.indexOf(b.topic_code))
const lessonRows = lessons.map(l => {
  const theme = Number(l.topic_code[0])
  const { topic_code, title, minutes, ...content } = l
  return `(${[lit(topic_code), theme, lit(theme <= 2 ? 'AS' : 'A'), order.indexOf(topic_code), lit(title), minutes, json(content)].join(', ')})`
})

const mocks = read('seed/mocks/').sort((a, b) => a.id.localeCompare(b.id))
const qs = mocks.flatMap(m => m.questions)
const qRows = qs.map(q => `(${[lit(q.id), q.theme, lit(q.topic_code), lit(q.level), lit(q.type), q.marks, lit(q.prompt), lit(q.context),
  q.options ? json(q.options) : 'null', "'mock'"].join(', ')})`)
const kRows = qs.map(q => `(${[lit(q.id), lit(q.answer), lit(q.explanation), lit(q.mark_scheme)].join(', ')})`)
const eRows = mocks.map(m => `(${[lit(m.id), lit(m.title), lit(m.description), lit(m.level), "'mock'", m.duration_minutes, 'true', 'true', lit(m.paper), 'null'].join(', ')})`)
const eqRows = mocks.flatMap(m => m.questions.map((q, i) => `(${[lit(m.id), lit(q.id), i, lit(q.section)].join(', ')})`))

const sql = `-- Generated by scripts/seed-content.mjs — ${lessons.length} lessons, ${mocks.length} mock papers (${qs.length} questions)

insert into public.lessons (topic_code, theme, level, position, title, minutes, content) values
${lessonRows.join(',\n')}
on conflict (topic_code) do update set theme = excluded.theme, level = excluded.level, position = excluded.position,
  title = excluded.title, minutes = excluded.minutes, content = excluded.content, updated_at = now();

insert into public.questions (id, theme, topic_code, level, type, marks, prompt, context, options, source) values
${qRows.join(',\n')}
on conflict (id) do update set theme = excluded.theme, topic_code = excluded.topic_code, level = excluded.level,
  type = excluded.type, marks = excluded.marks, prompt = excluded.prompt, context = excluded.context, options = excluded.options,
  source = excluded.source;

insert into public.question_keys (question_id, answer, explanation, mark_scheme) values
${kRows.join(',\n')}
on conflict (question_id) do update set answer = excluded.answer, explanation = excluded.explanation, mark_scheme = excluded.mark_scheme;

insert into public.exams (slug, title, description, level, kind, duration_minutes, published, library, paper, created_by) values
${eRows.join(',\n')}
on conflict (slug) do update set title = excluded.title, description = excluded.description, level = excluded.level,
  duration_minutes = excluded.duration_minutes, paper = excluded.paper;

-- question lists are only (re)written for papers nobody has started
insert into public.exam_questions (exam_id, question_id, position, section)
select e.id, v.qid, v.pos, v.section
from (values
${eqRows.join(',\n')}
) as v (slug, qid, pos, section)
join public.exams e on e.slug = v.slug
where not exists (select 1 from public.attempts a where a.exam_id = e.id)
on conflict (exam_id, question_id) do update set position = excluded.position, section = excluded.section;
`
writeFileSync(new URL('supabase/migrations/20261101000013_course_content.sql', root), sql)
console.log(`wrote ${lessons.length} lessons, ${mocks.length} mocks, ${qs.length} questions (${Math.round(sql.length / 1024)} KB)`)
