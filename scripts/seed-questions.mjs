// Generates supabase/migrations/20261101000004_questions.sql from seed/questions.json
import { readFileSync, writeFileSync } from 'node:fs'

const qs = JSON.parse(readFileSync(new URL('../seed/questions.json', import.meta.url)))
const lit = v => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)

const ids = new Set()
for (const q of qs) {
  if (ids.has(q.id)) throw new Error(`duplicate id ${q.id}`)
  ids.add(q.id)
  if (q.type === 'mcq' && !(q.options?.length && /^[A-D]$/.test(q.answer))) throw new Error(`bad mcq ${q.id}`)
}

const rows = qs.map(q => `(${[
  lit(q.id), q.theme, lit(q.topic_code), lit(q.level), lit(q.type), q.marks, lit(q.prompt), lit(q.context),
  q.options ? `${lit(JSON.stringify(q.options))}::jsonb` : 'null',
].join(', ')})`)
const keys = qs.map(q => `(${[lit(q.id), lit(q.answer), lit(q.explanation), lit(q.mark_scheme)].join(', ')})`)

writeFileSync(new URL('../supabase/migrations/20261101000004_questions.sql', import.meta.url), `-- Generated by scripts/seed-questions.mjs — original practice questions (${qs.length})
insert into public.questions (id, theme, topic_code, level, type, marks, prompt, context, options) values
${rows.join(',\n')}
on conflict (id) do update set theme = excluded.theme, topic_code = excluded.topic_code, level = excluded.level,
  type = excluded.type, marks = excluded.marks, prompt = excluded.prompt, context = excluded.context, options = excluded.options;

insert into public.question_keys (question_id, answer, explanation, mark_scheme) values
${keys.join(',\n')}
on conflict (question_id) do update set answer = excluded.answer, explanation = excluded.explanation, mark_scheme = excluded.mark_scheme;
`)
console.log(`wrote ${qs.length} questions`)
